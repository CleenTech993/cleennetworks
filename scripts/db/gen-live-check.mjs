#!/usr/bin/env node
// Generates supabase/verify_live_db.sql: a read-only query that tells you which migrations your
// LIVE database has fully, partly, or not at all.
//
// How: apply the migrations one at a time to a scratch Postgres, snapshot the public schema after
// each (scripts/db/snapshot.sql), and attribute every object that survives to the first migration
// that introduced it. The generated query then looks those objects up in the live catalog.
//
//   PGHOST/PGUSER/... must reach a superuser-capable Postgres (the scratch DB is recreated):
//   node scripts/db/gen-live-check.mjs            write supabase/verify_live_db.sql
//   node scripts/db/gen-live-check.mjs --stdout   print instead (used by the staleness check)
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
const DB = "live_check_gen";
const sh = (cmd, args = [], input) =>
  execFileSync(cmd, args, {
    cwd: root,
    encoding: "utf8",
    input,
    stdio: ["pipe", "pipe", "pipe"],
    maxBuffer: 1 << 28,
  });
const lib = (body) => sh("bash", ["-c", `source tests/sql/build-db.sh; ${body}`]);

const files = lib("migration_order").trim().split("\n");
const snapshotSql = readFileSync(join(root, "scripts/db/snapshot.sql"), "utf8").trim();
const snapshot = () =>
  new Set(
    sh("psql", ["-X", "-tA", "-F", "\t", "-d", DB, "-c", snapshotSql]).split("\n").filter(Boolean),
  );

lib(`init_db ${DB}`);
const base = snapshot();
let prev = base;
const introduced = new Map(); // "kind\tident" -> index of the migration that first created it
const tablesCreatedBy = new Map(); // table ident -> index
files.forEach((file, i) => {
  lib(`DB=${DB}; apply ${JSON.stringify(file)}`);
  const now = snapshot();
  for (const row of now) {
    if (prev.has(row) || introduced.has(row)) continue;
    introduced.set(row, i);
    const [kind, ident] = row.split("\t");
    if (kind === "table") tablesCreatedBy.set(ident, i);
  }
  prev = now;
});
const final = prev;
sh("psql", ["-X", "-q", "-d", "postgres", "-c", `DROP DATABASE IF EXISTS ${DB}`]);

// Objects that exist at the end, attributed to the migration that introduced them. A column on a
// table created by the same migration adds nothing (the table check covers it), so it is dropped.
const perFile = files.map(() => []);
for (const [row, i] of introduced) {
  if (!final.has(row)) continue;
  const [kind, ident] = row.split("\t");
  if (kind === "column") {
    const table = ident.split(".").slice(0, 2).join(".");
    if (tablesCreatedBy.get(table) === i) continue;
  }
  perFile[i].push([kind, ident]);
}

const q = (s) => `'${s.replace(/'/g, "''")}'`;
const rows = [];
files.forEach((file, i) => {
  const track = file.startsWith("drizzle/") ? "drizzle" : "supabase";
  const name = basename(file);
  const objs = perFile[i].sort((a, b) => (a[0] + a[1]).localeCompare(b[0] + b[1]));
  if (!objs.length) rows.push(`  (${i + 1}, ${q(track)}, ${q(name)}, 'none', '')`);
  for (const [kind, ident] of objs)
    rows.push(`  (${i + 1}, ${q(track)}, ${q(name)}, ${q(kind)}, ${q(ident)})`);
});

const out = `-- GENERATED by scripts/db/gen-live-check.mjs. Do not edit by hand: change a migration, then run
--   npm run db:verify-gen
-- READ-ONLY. Paste the whole file into Supabase Dashboard -> SQL Editor and run it.
--
-- One row per migration, in the order they must be applied:
--   OK           every object that migration creates is present in this database
--   PARTIAL      some are missing: the migration was cut short or edited by hand. Re-run it
--                (the October 2026 migrations are written to be safely re-runnable).
--   NOT APPLIED  none of its objects exist: apply it (and every later one)
--   n/a          it only changes data or defaults, so there is nothing to look up by name
-- Look at the 'missing_objects' column to see exactly what is absent.
--
-- Not covered: row data, column defaults, function bodies, grants, and cron jobs. For cron run
--   select jobname, schedule from cron.job;     -- expect the router liveness check
with expected(ord, track, migration, kind, ident) as (values
${rows.join(",\n")}
),
live(kind, ident) as (
${snapshotSql}
),
checked as (
  select e.ord, e.track, e.migration, e.kind, e.ident, (l.ident is not null) as present
    from expected e
    left join live l on l.kind = e.kind and l.ident = e.ident
)
select ord,
       track,
       migration,
       count(*) filter (where kind <> 'none') as objects,
       count(*) filter (where kind <> 'none' and present) as found,
       count(*) filter (where kind <> 'none' and not present) as missing,
       case
         when count(*) filter (where kind <> 'none') = 0 then 'n/a'
         when count(*) filter (where kind <> 'none' and not present) = 0 then 'OK'
         when count(*) filter (where kind <> 'none' and present) = 0 then 'NOT APPLIED'
         else 'PARTIAL'
       end as status,
       case when count(*) filter (where kind <> 'none' and not present) = 0 then null
            else array_to_string((array_agg(kind || ' ' || ident order by kind, ident)
                                    filter (where kind <> 'none' and not present))[1:20], E'\\n')
                 || case when count(*) filter (where kind <> 'none' and not present) > 20
                         then E'\\n... and ' || (count(*) filter (where kind <> 'none' and not present) - 20) || ' more'
                         else '' end
       end as missing_objects
  from checked
 group by ord, track, migration
 order by ord;
`;

if (process.argv.includes("--stdout")) process.stdout.write(out);
else {
  writeFileSync(join(root, "supabase/verify_live_db.sql"), out);
  console.log(
    `wrote supabase/verify_live_db.sql: ${files.length} migrations, ${rows.filter((r) => !r.includes("'none'")).length} checked objects`,
  );
}
